-- Definer functions: the only way across tenants. They return tenant ids or a boolean, never rows.
-- +goose StatementBegin
CREATE FUNCTION mailrules_tenants(kind text) RETURNS SETOF bigint
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  CASE kind
    WHEN 'all' THEN RETURN QUERY SELECT id FROM tenants ORDER BY id;
    WHEN 'notices' THEN RETURN QUERY SELECT DISTINCT tenant_id FROM notices WHERE handed_at IS NULL ORDER BY 1;
    WHEN 'moves' THEN RETURN QUERY SELECT DISTINCT tenant_id FROM moves WHERE handed_at IS NULL ORDER BY 1;
    WHEN 'removed' THEN RETURN QUERY SELECT DISTINCT tenant_id FROM removed_mailboxes ORDER BY 1;
    WHEN 'forgotten' THEN RETURN QUERY SELECT DISTINCT tenant_id FROM forgotten ORDER BY 1;
    ELSE RAISE EXCEPTION 'mailrules_tenants: unknown kind %', kind;
  END CASE;
END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION mailrules_tenant_of(kind text, key text, key2 text DEFAULT NULL) RETURNS bigint
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  t bigint;
BEGIN
  CASE kind
    WHEN 'account' THEN SELECT tenant_id INTO t FROM accounts WHERE id = key::bigint;
    WHEN 'message' THEN SELECT tenant_id INTO t FROM messages WHERE id = key::bigint;
    WHEN 'action' THEN SELECT tenant_id INTO t FROM actions WHERE id = key::bigint;
    WHEN 'batch' THEN SELECT tenant_id INTO t FROM batches WHERE id = key::bigint;
    WHEN 'user' THEN SELECT tenant_id INTO t FROM users WHERE id = key::bigint;
    WHEN 'destination' THEN SELECT tenant_id INTO t FROM notify_destinations WHERE id = key::bigint;
    WHEN 'notice' THEN SELECT tenant_id INTO t FROM notices WHERE id = key::bigint;
    WHEN 'move' THEN SELECT tenant_id INTO t FROM moves WHERE id = key::bigint;
    WHEN 'question' THEN SELECT tenant_id INTO t FROM move_questions WHERE id = key::bigint;
    WHEN 'removed' THEN SELECT tenant_id INTO t FROM removed_mailboxes WHERE id = key::bigint;
    WHEN 'summary' THEN SELECT tenant_id INTO t FROM summaries WHERE id = key::bigint;
    WHEN 'rule' THEN SELECT tenant_id INTO t FROM rules WHERE id = key::bigint;
    WHEN 'sender_rule' THEN SELECT tenant_id INTO t FROM sender_rules WHERE id = key::bigint;
    WHEN 'session' THEN SELECT tenant_id INTO t FROM sessions WHERE token_hash = key;
    WHEN 'email' THEN SELECT tenant_id INTO t FROM users WHERE lower(email) = lower(key) LIMIT 1;
    WHEN 'identity' THEN SELECT tenant_id INTO t FROM identities WHERE provider = key AND subject = key2;
    WHEN 'external' THEN SELECT id INTO t FROM tenants WHERE provider = key AND external_id = key2;
    WHEN 'first_user' THEN SELECT tenant_id INTO t FROM users ORDER BY id LIMIT 1;
    ELSE RAISE EXCEPTION 'mailrules_tenant_of: unknown kind %', kind;
  END CASE;
  RETURN t;
END
$$;
-- +goose StatementEnd

