-- Two first sign-ins of one organisation at once both get its one tenant: the second waits
-- for the first's insert, then reads it (each statement of a VOLATILE function sees what was
-- committed before it began).
CREATE FUNCTION mailrules_create_tenant(provider text, external_id text, created_at bigint) RETURNS bigint
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
#variable_conflict use_column
DECLARE
  t bigint;
BEGIN
  INSERT INTO tenants (provider, external_id, created_at) VALUES ($1, $2, $3)
  ON CONFLICT (provider, external_id) DO NOTHING RETURNING id INTO t;
  IF t IS NULL THEN
    SELECT id INTO t FROM tenants WHERE tenants.provider = $1 AND tenants.external_id = $2;
  END IF;
  RETURN t;
END
$$;
