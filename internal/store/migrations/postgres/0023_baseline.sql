-- A row inserted without tenant_id and outside any tenant scope (a superuser seeding test
-- rows, as SQLite has no such column) takes its parent row's tenant. It runs as the
-- inserting role, so RLS still applies: an unscoped app role sees no parent, tenant_id
-- stays NULL and NOT NULL refuses the row.
-- +goose StatementBegin
CREATE FUNCTION mailrules_fill_tenant() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER AS $$
DECLARE
  parent_id bigint := (to_jsonb(NEW) ->> TG_ARGV[1])::bigint;
BEGIN
  IF parent_id IS NOT NULL THEN
    EXECUTE format('SELECT tenant_id FROM %I WHERE id = $1', TG_ARGV[0])
      INTO NEW.tenant_id USING parent_id;
  END IF;
  RETURN NEW;
END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
DO $$
DECLARE
  r text[];
BEGIN
  FOREACH r SLICE 1 IN ARRAY ARRAY[
    ['accounts', 'users', 'user_id'],
    ['messages', 'accounts', 'account_id'],
    ['rules', 'users', 'user_id'],
    ['batches', 'accounts', 'account_id'],
    ['decisions', 'messages', 'message_id'],
    ['actions', 'accounts', 'account_id'],
    ['contacts', 'accounts', 'account_id'],
    ['corrections', 'messages', 'message_id'],
    ['folders', 'accounts', 'account_id'],
    ['forgotten', 'users', 'user_id'],
    ['identities', 'users', 'user_id'],
    ['notices', 'accounts', 'account_id'],
    ['notify_deliveries', 'notify_destinations', 'destination_id'],
    ['moves', 'accounts', 'account_id'],
    ['move_questions', 'accounts', 'account_id'],
    ['sender_rules', 'users', 'user_id'],
    ['sessions', 'users', 'user_id'],
    ['summaries', 'users', 'user_id'],
    ['unsubscribes', 'accounts', 'account_id']
  ] LOOP
    EXECUTE format('CREATE TRIGGER mailrules_fill_tenant BEFORE INSERT ON %I FOR EACH ROW '
      'WHEN (NEW.tenant_id IS NULL) EXECUTE FUNCTION mailrules_fill_tenant(%L, %L)', r[1], r[2], r[3]);
  END LOOP;
END
$$;
-- +goose StatementEnd

-- Row-level security: every table, the owner included (FORCE).
-- +goose StatementBegin
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users', 'accounts', 'messages', 'rules', 'batches', 'decisions', 'actions',
    'ai_emails', 'contacts', 'corrections', 'first_cleanup', 'folders', 'forgotten',
    'identities', 'notify_destinations', 'notices', 'notify_deliveries', 'moves',
    'move_questions', 'removed_mailboxes', 'sender_rules', 'sessions', 'settings',
    'summaries', 'unsubscribes', 'usage_daily'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY mailrules_tenant ON %I USING (tenant_id = mailrules_tenant()) WITH CHECK (tenant_id = mailrules_tenant())', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO mailrules_app', t);
    IF t NOT IN ('users', 'sessions') THEN
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO mailrules_worker', t);
    END IF;
  END LOOP;

  -- Tables the definer functions read.
  FOREACH t IN ARRAY ARRAY[
    'tenants', 'users', 'accounts', 'messages', 'actions', 'batches', 'rules',
    'notify_destinations', 'notices', 'moves', 'move_questions', 'removed_mailboxes',
    'summaries', 'sessions', 'identities', 'forgotten', 'sender_rules'
  ] LOOP
