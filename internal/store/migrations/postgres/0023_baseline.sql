-- Postgres baseline: the SQLite schema as of migration 0023, with every row
-- scoped to a tenant by row-level security. Requires Postgres 16+.

-- +goose Up

-- Group roles. Cluster-wide, so created only when missing and never dropped.
-- +goose StatementBegin
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'mailrules_app') THEN
    CREATE ROLE mailrules_app NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'mailrules_worker') THEN
    CREATE ROLE mailrules_worker NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'mailrules_definer') THEN
    CREATE ROLE mailrules_definer NOLOGIN;
  END IF;
  -- The owner hands the definer functions to mailrules_definer, which needs SET.
  IF NOT pg_has_role(current_user, 'mailrules_definer', 'SET') THEN
    EXECUTE format('GRANT mailrules_definer TO %I WITH INHERIT FALSE, SET TRUE', current_user);
  END IF;
END
$$;
-- +goose StatementEnd

-- The tenant the current transaction is scoped to; NULL when none.
-- +goose StatementBegin
CREATE FUNCTION mailrules_tenant() RETURNS bigint LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('app.tenant_id', true), '')::bigint
$$;
-- +goose StatementEnd

CREATE TABLE tenants (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider    TEXT,                       -- the sign-in service that made it; NULL = self-host
  external_id TEXT,                       -- that service's organisation id
  created_at  BIGINT NOT NULL,
  UNIQUE (provider, external_id)
);

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,              -- argon2id encoded string
  created_at    BIGINT NOT NULL,
  tenant_id     BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  UNIQUE (tenant_id, id)
);

CREATE TABLE accounts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL,
  label         TEXT NOT NULL,
  preset        TEXT NOT NULL,              -- icloud | fastmail | yahoo | zoho | generic
  host          TEXT NOT NULL,
  port          BIGINT NOT NULL DEFAULT 993,
  tls_mode      TEXT NOT NULL DEFAULT 'implicit',  -- implicit | starttls
  username      TEXT NOT NULL,
  secret_enc    BYTEA NOT NULL,             -- envelope-encrypted app password or token
  dek_enc       BYTEA NOT NULL,             -- per-account data key, wrapped by master key
  watch_folder  TEXT NOT NULL DEFAULT 'INBOX',
  status        TEXT NOT NULL DEFAULT 'new', -- new | live | reconnecting | auth_failed | error | paused
  last_error    TEXT,
  last_event_at BIGINT,
  capabilities  TEXT,                       -- JSON array from CAPABILITY
  created_at    BIGINT NOT NULL,
  tenant_id     BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  shared        BOOLEAN NOT NULL DEFAULT FALSE,
  cert_fingerprint TEXT NOT NULL DEFAULT '',
  oauth         BOOLEAN NOT NULL DEFAULT FALSE,
  module        BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id)
);

CREATE TABLE messages (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id     BIGINT NOT NULL,
  folder         TEXT NOT NULL,
  uidvalidity    BIGINT NOT NULL,
  uid            BIGINT NOT NULL,
  message_id     TEXT,                      -- RFC 5322 Message-ID
  from_addr      TEXT, from_domain TEXT, to_addrs TEXT, subject TEXT,
  from_name      TEXT,                      -- the From display name, shown on the Senders screen
  snippet        TEXT,                      -- first 200 chars, purged after retention
  received_at    BIGINT,
  list_id        TEXT,
  has_attachment BOOLEAN NOT NULL DEFAULT FALSE,
  size           BIGINT,
  signals        TEXT,                      -- JSON: bulk, noreply, dmarc, replied_before, list_unsubscribe ...
  state          TEXT NOT NULL DEFAULT 'new', -- new | decided | acted | review | skipped | error
  attempts       BIGINT NOT NULL DEFAULT 0, -- retries made after a failure
  next_attempt_at BIGINT,                   -- when the retry job runs it again; NULL = not waiting
  cur_folder     TEXT,                      -- where the executor last left it; NULL = still where it arrived
  cur_uidvalidity BIGINT,
  cur_uid        BIGINT,
  created_at     BIGINT NOT NULL, acted_at BIGINT NOT NULL DEFAULT 0, unsubscribe_url TEXT,
  metered        BOOLEAN NOT NULL DEFAULT FALSE,
  tenant_id      BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  UNIQUE (account_id, folder, uidvalidity, uid),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE rules (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        BIGINT NOT NULL,
  account_id     BIGINT,                    -- NULL = all accounts
  name           TEXT NOT NULL,
  said           TEXT,                      -- user's original wording
  intent         TEXT,                      -- optimized plain-English intent; NULL = condition-only
  conditions     TEXT NOT NULL DEFAULT '{}',-- JSON condition tree
  exceptions     TEXT NOT NULL DEFAULT '{}',-- JSON condition tree ("unless")
  actions        TEXT NOT NULL,             -- JSON array of actions
  priority       BIGINT NOT NULL,           -- lower runs first
  stack          BOOLEAN NOT NULL DEFAULT FALSE, -- also apply after a match
  model          TEXT,                      -- per-rule decider override
  min_confidence DOUBLE PRECISION,
  enabled        BOOLEAN NOT NULL DEFAULT TRUE,
  version        BIGINT NOT NULL DEFAULT 1,
  created_at     BIGINT NOT NULL,
  updated_at     BIGINT NOT NULL,
  template       TEXT,
  mailbox_removed BOOLEAN NOT NULL DEFAULT FALSE,
  tenant_id      BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  notify         TEXT NOT NULL DEFAULT '[]',
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id),
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE batches (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       TEXT NOT NULL,                 -- live | cleanup | review | correction | undo
  status     TEXT NOT NULL,                 -- running | done | failed | undone
  total      BIGINT, done BIGINT NOT NULL DEFAULT 0,
  account_id BIGINT,                        -- cleanup: the mailbox it sorted
  folder     TEXT,                          -- cleanup: the folder
  since      BIGINT,                        -- cleanup: only mail received from this time on; NULL = all of it
  tokens     BIGINT NOT NULL DEFAULT 0,     -- cleanup: model tokens used so far, in and out
  cost_usd   DOUBLE PRECISION NOT NULL DEFAULT 0, -- cleanup: model cost so far
  created_at BIGINT NOT NULL,
  skipped    BIGINT NOT NULL DEFAULT 0, scan_limit BIGINT, scan_matched BIGINT, run_id BIGINT,
  tenant_id  BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id) ON DELETE SET NULL (account_id)
);

CREATE TABLE decisions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id  BIGINT NOT NULL,
  stage       TEXT NOT NULL,                -- sender | condition | decider | fallback | none
  rule_id     BIGINT,
  rule_name   TEXT,                         -- the rule's name when decided; survives deleting the rule
  rule_version BIGINT,
  confidence  DOUBLE PRECISION,
  reason      TEXT,
  model       TEXT,
  tokens_in   BIGINT, tokens_out BIGINT,
  cost_usd    DOUBLE PRECISION, latency_ms BIGINT,
  probabilities TEXT,                       -- JSON {"<rule id>": p, "0": p for none}; NULL when none given
  created_at  BIGINT NOT NULL,
  sender_source TEXT,
  tenant_id   BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, message_id) REFERENCES messages (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, rule_id) REFERENCES rules (tenant_id, id) ON DELETE SET NULL (rule_id)
);

CREATE TABLE actions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id BIGINT,
  batch_id    BIGINT,
  message_id  BIGINT NOT NULL,
  account_id  BIGINT NOT NULL,
  kind        TEXT NOT NULL,                -- move | trash | archive | junk | flag | unflag | read | unread | keep | review
  params      TEXT,                         -- JSON, e.g. {"folder":"Food"}
  before      TEXT NOT NULL,                -- JSON {folder, uidvalidity, uid, flags[]}
  after       TEXT,                         -- JSON {folder, uidvalidity, uid, flags[]}
  status      TEXT NOT NULL,                -- done | dry_run | failed | undone
  error       TEXT,
  created_at  BIGINT NOT NULL,
  undone_at   BIGINT,
  tenant_id   BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, decision_id) REFERENCES decisions (tenant_id, id),
  FOREIGN KEY (tenant_id, batch_id) REFERENCES batches (tenant_id, id),
  FOREIGN KEY (tenant_id, message_id) REFERENCES messages (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id) ON DELETE CASCADE
);

