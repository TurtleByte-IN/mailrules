-- +goose Up
-- The Team plan (MAI-234), as sqlite/0029_team.sql describes it, kept to its tenant like
-- every table (0023).
--
-- Everyone who exists now becomes an owner: the column is added with that default, which
-- fills the existing rows without reading them (no tenant scope is needed), then the default
-- becomes member.
ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'owner' CHECK (role IN ('owner', 'admin', 'member'));
ALTER TABLE users ALTER COLUMN role SET DEFAULT 'member';
-- Workers read a user's role with the rest of what they may read of users.
GRANT SELECT (role) ON users TO mailrules_worker;

CREATE TABLE invitations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  email       TEXT NOT NULL,
  role        TEXT NOT NULL CHECK (role IN ('owner', 'admin', 'member')),
  invited_by  BIGINT,
  record      TEXT NOT NULL DEFAULT '',
  created_at  BIGINT NOT NULL,
  expires_at  BIGINT NOT NULL,
  accepted_at BIGINT
);
CREATE UNIQUE INDEX invitations_email ON invitations(tenant_id, lower(email));

CREATE TABLE audit_log (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  at        BIGINT NOT NULL,
  actor_id  BIGINT,
  actor     TEXT NOT NULL,
  action    TEXT NOT NULL,
  target    TEXT NOT NULL DEFAULT '',
  detail    TEXT NOT NULL DEFAULT ''
);
CREATE INDEX audit_log_tenant ON audit_log(tenant_id, at);
-- +goose StatementBegin
CREATE FUNCTION mailrules_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'the audit log is append-only';
END
$$;
-- +goose StatementEnd
CREATE TRIGGER audit_log_append_only BEFORE UPDATE ON audit_log
  FOR EACH ROW EXECUTE FUNCTION mailrules_append_only();

ALTER TABLE invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE invitations FORCE ROW LEVEL SECURITY;
CREATE POLICY mailrules_tenant ON invitations USING (tenant_id = mailrules_tenant()) WITH CHECK (tenant_id = mailrules_tenant());
GRANT SELECT, INSERT, UPDATE, DELETE ON invitations TO mailrules_app, mailrules_worker;

ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log FORCE ROW LEVEL SECURITY;
CREATE POLICY mailrules_tenant ON audit_log USING (tenant_id = mailrules_tenant()) WITH CHECK (tenant_id = mailrules_tenant());
-- Append-only: no role may change a row; the retention job and a tenant's removal delete.
GRANT SELECT, INSERT, DELETE ON audit_log TO mailrules_app, mailrules_worker;

