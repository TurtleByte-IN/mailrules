CREATE TABLE draft_jobs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     BIGINT NOT NULL DEFAULT mailrules_tenant() REFERENCES tenants(id) ON DELETE CASCADE,
  account_id    BIGINT NOT NULL,
  message_id    BIGINT NOT NULL,
  decision_id   BIGINT NOT NULL,
  batch_id      BIGINT NOT NULL,
  rule_id       BIGINT,
  rule_name     TEXT NOT NULL,
  instruction   TEXT NOT NULL DEFAULT '',
  read_previous BOOLEAN NOT NULL DEFAULT FALSE,
  draft_key     TEXT NOT NULL,
  created_at    BIGINT NOT NULL,
  attempts      BIGINT NOT NULL DEFAULT 0,
  next_at       BIGINT NOT NULL,
  FOREIGN KEY (tenant_id, account_id) REFERENCES accounts (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, message_id) REFERENCES messages (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, rule_id) REFERENCES rules (tenant_id, id) ON DELETE SET NULL (rule_id)
);
CREATE INDEX draft_jobs_next ON draft_jobs(next_at);
CREATE INDEX draft_jobs_message ON draft_jobs(message_id);
